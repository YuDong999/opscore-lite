func TestQuoteValue(t *testing.T) {
	if quoteValue(nil, DialectMySQL, "") != "NULL" {
		t.Error("nil 应为 NULL")
	}
	if quoteValue(true, DialectMySQL, "") != "1" || quoteValue(true, DialectPostgres, "") != "TRUE" {
		t.Error("bool 方言不符")
	}
	if got := quoteValue(`he said "hi" \ 'x'`, DialectMySQL, ""); got != `'he said "hi" \\ \'x\''` {
		t.Errorf("MySQL 转义不符: %s", got)
	}
	if got := quoteValue(`it's`, DialectPostgres, ""); got != `'it''s'` {
		t.Errorf("PG 转义不符: %s", got)
	}
	if got := quoteValue([]byte{0xDE, 0xAD}, DialectMySQL, "blob"); got != "X'dead'" {
		t.Errorf("MySQL bytea 不符: %s", got)
	}
	if got := quoteValue([]byte{0xDE, 0xAD}, DialectPostgres, "bytea"); got != `'\xdead'` {
		t.Errorf("PG bytea 不符: %s", got)
	}
	// boolean 目标列收到数字/字符串(驱动归一化后)
	if quoteValue(int64(1), DialectPostgres, "boolean") != "TRUE" || quoteValue(int64(0), DialectPostgres, "boolean") != "FALSE" {
		t.Error("int→boolean 不符")
	}
	if quoteValue("1", DialectPostgres, "boolean") != "TRUE" || quoteValue("0", DialectPostgres, "boolean") != "FALSE" {
		t.Error("string→boolean 不符")
	}
	// bytea 目标列收到 GoNavi 归一化的 "0x<hex>" 字符串
	if got := quoteValue("0xdead", DialectPostgres, "bytea"); got != `'\xdead'` {
		t.Errorf("string→bytea 不符: %s", got)
	}
	if got := quoteValue("0xdead", DialectMySQL, "blob"); got != "X'dead'" {
		t.Errorf("0x→MySQL blob 不符: %s", got)
	}
}

func TestBuildInsertSQL(t *testing.T) {
	sqlText := buildInsertSQL("db", "t", []string{"a", "b"}, map[string]string{"a": "integer", "b": "varchar"}, [][]any{{1, `x'y`}, {nil, int64(2)}}, DialectMySQL, 0)
	want := "INSERT INTO `db`.`t` (`a`, `b`) VALUES (1,'x\\'y'),\n(NULL,2)"
	if sqlText != want {
		t.Errorf("INSERT SQL 不符:\n got: %s\nwant: %s", sqlText, want)
	}
	// 列序与 colBases 按名字对齐: 流式列序乱序时 boolean/bytea 仍正确
	sqlText2 := buildInsertSQL("db", "t", []string{"flag", "data"}, map[string]string{"flag": "boolean", "data": "bytea"},
		[][]any{{int64(1), "0xdeadbeef"}}, DialectPostgres, 0)
	if !strings.Contains(sqlText2, "TRUE") || !strings.Contains(sqlText2, `'\xdeadbeef'`) {
		t.Errorf("乱序列对齐失败: %s", sqlText2)
	}
	// RFC3339 时间归一
	if got := quoteValue("2024-05-01T10:00:00+08:00", DialectPostgres, "timestamp"); got != "'2024-05-01 10:00:00'" {
		t.Errorf("RFC3339 归一不符: %s", got)
	}
}

func TestDetectIncremental(t *testing.T) {
	cols := []gonaviConnection.ColumnDefinition{
		{Name: "id", Type: "bigint", Key: "PRI", Extra: "auto_increment"},
		{Name: "updated_at", Type: "datetime"},
	}
	if c, s := detectIncremental(cols, ""); c != "id" || s != IncrAutoIncrement {
		t.Errorf("应探测自增主键: %s %s", c, s)
	}
	if c, s := detectIncremental(cols, "updated_at"); c != "updated_at" || s != IncrTimestamp {
		t.Errorf("应优先指定列: %s %s", c, s)
	}
	noIncr := []gonaviConnection.ColumnDefinition{{Name: "name", Type: "varchar(32)"}}
	if _, s := detectIncremental(noIncr, ""); s != IncrNone {
		t.Error("无增量列应返回 none")
	}
}

