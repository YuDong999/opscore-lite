func TestGenerateCreateDDLMySQLToPG(t *testing.T) {
	cols := []gonaviConnection.ColumnDefinition{
		{Name: "id", Type: "bigint", Nullable: "NO", Key: "PRI", Extra: "auto_increment"},
		{Name: "name", Type: "varchar(64)", Nullable: "NO"},
		{Name: "score", Type: "decimal(10,2)", Nullable: "YES"},
		{Name: "del", Type: "tinyint(1)", Nullable: "NO", Default: strPtr("0")},
		{Name: "attrs", Type: "json", Nullable: "YES"},
	}
	idx := []gonaviConnection.IndexDefinition{
		{Name: "PRIMARY", ColumnName: "id", NonUnique: 0, SeqInIndex: 1},
		{Name: "idx_name", ColumnName: "name", NonUnique: 1, SeqInIndex: 1},
	}
	ddl, idxDDL, _ := GenerateCreateDDL("targetdb", "users", cols, idx, DialectMySQL, DialectPostgres)
	for _, want := range []string{
		`"targetdb"."users"`,
		`"id" bigint GENERATED BY DEFAULT AS IDENTITY`,
		`"name" varchar(64) NOT NULL`,
		`"score" numeric(10,2)`,
		`"del" boolean NOT NULL DEFAULT FALSE`,
		`"attrs" jsonb`,
		`PRIMARY KEY ("id")`,
	} {
		if !strings.Contains(ddl, want) {
			t.Errorf("DDL 缺少 %q:\n%s", want, ddl)
		}
	}
	if len(idxDDL) != 1 || !strings.Contains(idxDDL[0], `CREATE INDEX IF NOT EXISTS "idx_name"`) {
		t.Errorf("索引 DDL 不符: %v", idxDDL)
	}
}

