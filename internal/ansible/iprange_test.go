package ansible

import (
	"fmt"
	"reflect"
	"testing"
)

func TestExpandIPRange(t *testing.T) {
	cases := []struct {
		name string
		in   string
		want []string
	}{
		{"单个IP", "192.168.94.1", []string{"192.168.94.1"}},
		{"后缀列表", "192.168.94.22/25", []string{"192.168.94.22", "192.168.94.25"}},
		{"后缀列表多段", "192.168.94.22/23/24/25", []string{"192.168.94.22", "192.168.94.23", "192.168.94.24", "192.168.94.25"}},
		{"CIDR网段", "192.168.94.0/30", []string{"192.168.94.0", "192.168.94.1", "192.168.94.2", "192.168.94.3"}},
		{"CIDR/24", "10.2.22.0/24", func() []string {
			var out []string
			for i := 0; i < 256; i++ {
				out = append(out, fmt.Sprintf("10.2.22.%d", i))
			}
			return out
		}()},
		{"末位简写范围", "192.168.94.22-30", []string{"192.168.94.22", "192.168.94.23", "192.168.94.24", "192.168.94.25", "192.168.94.26", "192.168.94.27", "192.168.94.28", "192.168.94.29", "192.168.94.30"}},
		{"完整IP范围", "10.2.22.1-10.2.22.3", []string{"10.2.22.1", "10.2.22.2", "10.2.22.3"}},
		{"跨段范围", "10.2.22.254-10.2.23.2", []string{"10.2.22.254", "10.2.22.255", "10.2.23.0", "10.2.23.1", "10.2.23.2"}},
		{"逗号列表", "10.2.22.1,10.2.22.2", []string{"10.2.22.1", "10.2.22.2"}},
		{"逗号混写", "10.2.22.1,192.168.94.22/23", []string{"10.2.22.1", "192.168.94.22", "192.168.94.23"}},
		{"逗号去重", "192.168.94.1,192.168.94.1", []string{"192.168.94.1"}},
	}
	for _, c := range cases {
		got, err := ExpandIPRange(c.in)
		if err != nil {
			t.Errorf("%s: %s 报错: %v", c.name, c.in, err)
			continue
		}
		if !reflect.DeepEqual(got, c.want) {
			t.Errorf("%s: %s\n got  %v\n want %v", c.name, c.in, got, c.want)
		}
	}

	errCases := []string{
		"192.168.94.30-22",
		"192.168.94.10.1-192.168.94.9.1",
		"192.168.94.22/300",
		"192.168.0.0/16",
		"abc",
		"",
	}
	for _, in := range errCases {
		if _, err := ExpandIPRange(in); err == nil {
			t.Errorf("应报错但成功: %s", in)
		}
	}
}
